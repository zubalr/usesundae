#!/usr/bin/env node
/**
 * Write the token vocabulary into AGENTS.md, between markers.
 *
 * A rule without a vocabulary costs two passes: the agent invents a value, the
 * hook rejects it, the agent looks up the real one. Listing the tokens where
 * the agent already reads makes the first pass correct.
 *
 * Runs as part of `npm run check`, so the list cannot go stale.
 */

import { readFileSync, writeFileSync, existsSync } from "node:fs";

const TOKEN_FILE = process.argv[2] ?? "app/globals.css";
const DOC = "AGENTS.md";
const START = "<!-- tokens:start -->";
const END = "<!-- tokens:end -->";

if (!existsSync(TOKEN_FILE)) process.exit(0);

const css = readFileSync(TOKEN_FILE, "utf8");

// semantic tokens only: primitives are prefixed --c- and are not for components
const names = [...css.matchAll(/^\s*(--[a-z][a-z0-9-]*)\s*:/gm)]
  .map((m) => m[1])
  .filter((n) => !n.startsWith("--c-"));

const GROUPS = [
  [
    "colour",
    (n) =>
      /^--(surface|border|accent|success|warning|focus)/.test(n) ||
      /^--text-(primary|secondary)/.test(n),
  ],
  ["space", (n) => n.startsWith("--space-")],
  ["type", (n) => /^--(font-|text-|leading-|weight-|measure)/.test(n)],
  ["shape", (n) => /radius-|shadow-/.test(n)],
  ["motion", (n) => /duration-|ease-/.test(n)],
];

const seen = new Set();
const lines = [];
for (const [label, test] of GROUPS) {
  const hit = names.filter((n) => !seen.has(n) && test(n));
  hit.forEach((n) => seen.add(n));
  if (hit.length) lines.push(`${label.padEnd(7)} ${hit.join(" ")}`);
}
const rest = names.filter((n) => !seen.has(n));
if (rest.length) lines.push(`other   ${rest.join(" ")}`);

const block = [
  START,
  "",
  "### Tokens available here",
  "",
  "Use these. Do not invent a value, and do not read the token file to find one —",
  "this list is regenerated by `npm run check`, so it is current.",
  "",
  "```",
  ...lines,
  "```",
  "",
  `Defined in \`${TOKEN_FILE}\`. Need one that does not exist? Add it there, in both`,
  "themes, and rerun `npm run check`. Never inline the raw value instead.",
  "",
  END,
].join("\n");

let doc = existsSync(DOC) ? readFileSync(DOC, "utf8") : "# AGENTS\n";
const i = doc.indexOf(START);
const j = doc.indexOf(END);

const next =
  i !== -1 && j !== -1
    ? doc.slice(0, i) + block + doc.slice(j + END.length)
    : doc.trimEnd() + "\n\n" + block + "\n";

if (next !== doc) {
  writeFileSync(DOC, next);
  console.log(`Token vocabulary synced to ${DOC} — ${names.length} tokens.`);
} else {
  console.log(`Token vocabulary current — ${names.length} tokens.`);
}
